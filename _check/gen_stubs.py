"""从 XAML 里提取 x:Class / x:Name，生成用于编译校验的桩类。

只服务于 _check 校验工程，不参与正式构建。
"""
import os
import re
import sys

TAG_TYPES = {
    "Window": "System.Windows.Window",
    "Grid": "System.Windows.Controls.Grid",
    "StackPanel": "System.Windows.Controls.StackPanel",
    "WrapPanel": "System.Windows.Controls.WrapPanel",
    "DockPanel": "System.Windows.Controls.DockPanel",
    "Canvas": "System.Windows.Controls.Canvas",
    "Border": "System.Windows.Controls.Border",
    "TextBlock": "System.Windows.Controls.TextBlock",
    "TextBox": "System.Windows.Controls.TextBox",
    "Button": "System.Windows.Controls.Button",
    "CheckBox": "System.Windows.Controls.CheckBox",
    "ComboBox": "System.Windows.Controls.ComboBox",
    "ComboBoxItem": "System.Windows.Controls.ComboBoxItem",
    "ListBox": "System.Windows.Controls.ListBox",
    "ListView": "System.Windows.Controls.ListView",
    "Image": "System.Windows.Controls.Image",
    "Rectangle": "System.Windows.Shapes.Rectangle",
    "Ellipse": "System.Windows.Shapes.Ellipse",
    "ScrollViewer": "System.Windows.Controls.ScrollViewer",
    "Viewbox": "System.Windows.Controls.Viewbox",
    "ProgressBar": "System.Windows.Controls.ProgressBar",
    "TabControl": "System.Windows.Controls.TabControl",
    "TabItem": "System.Windows.Controls.TabItem",
    "Slider": "System.Windows.Controls.Slider",
    "Separator": "System.Windows.Controls.Separator",
    "Menu": "System.Windows.Controls.Menu",
}

CLASS_RE = re.compile(r'x:Class="([^"]+)"')
NAME_RE = re.compile(r'<([A-Za-z_][\w\.]*)\b[^<>]*?x:Name="([^"]+)"', re.S)


def collect(xaml_path):
    with open(xaml_path, "r", encoding="utf-8-sig") as handle:
        text = handle.read()
    match = CLASS_RE.search(text)
    if not match:
        return None
    full = match.group(1)
    ns, _, cls = full.rpartition(".")
    fields = []
    seen = set()
    for tag, name in NAME_RE.findall(text):
        if name in seen:
            continue
        seen.add(name)
        short_tag = tag.split(".")[-1]
        clr = TAG_TYPES.get(short_tag, "System.Windows.FrameworkElement")
        fields.append((clr, name))
    return ns, cls, fields


def main():
    root = sys.argv[1]
    out = sys.argv[2]
    lines = ["// <auto-generated /> 编译校验用桩代码，正式项目不使用", "using System;", ""]
    count = 0
    for base, _dirs, files in os.walk(root):
        if "obj" in base or "bin" in base:
            continue
        for name in sorted(files):
            if not name.endswith(".xaml"):
                continue
            info = collect(os.path.join(base, name))
            if not info:
                continue
            ns, cls, fields = info
            lines.append("namespace %s" % ns)
            lines.append("{")
            lines.append("    public partial class %s" % cls)
            lines.append("    {")
            for clr, fname in fields:
                lines.append("        internal global::%s %s;" % (clr, fname))
            lines.append("        public void InitializeComponent() { }")
            lines.append("    }")
            lines.append("}")
            lines.append("")
            count += 1
    with open(out, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    print("generated stubs for %d xaml files -> %s" % (count, out))


if __name__ == "__main__":
    main()
